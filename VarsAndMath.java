public class VarsAndMath {
    public static void main(String[] args) {
        int a = 10;
        double b = 5.5;
        double sum = a + b;
        double product = a * b;

        System.out.println("The sum of " + a + " and " + b + " is " + sum);
        System.out.println("The product of " + a + " and " + b + " is " + product);


    }
}
